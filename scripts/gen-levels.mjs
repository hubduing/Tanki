/** Состав врагов: ровно 20 штук, с ростом сложности по номеру уровня. */
function enemiesFor(n) {
  const b = Math.max(2, 10 - Math.floor(n / 2));
  const f = Math.min(6, 2 + Math.floor(n / 3));
  const p = Math.min(5, 2 + Math.floor(n / 4));
  const a = 20 - b - f - p;
  if (a < 0) throw new Error(`уровень ${n}: состав не сходится`);
  return [...Array(b).fill('B'), ...Array(f).fill('F'), ...Array(p).fill('P'), ...Array(a).fill('A')];
}

/** Собирает сетку 13×13: верхняя часть из шаблона, низ — базовый каркас. */
function buildMap(pattern) {
  if (pattern.length !== 9) throw new Error('шаблон должен содержать 9 строк');
  const rows = [...pattern];
  for (const row of BASE_ROWS) rows.push(row);
  for (const [i, row] of rows.entries()) {
    if (row.length !== 13) throw new Error(`строка ${i}: длина ${row.length}, ожидается 13`);
    if (!/^[.#@~*=E]+$/.test(row)) throw new Error(`строка ${i}: недопустимый символ`);
  }
  const flat = rows.join('');
  const eCount = [...flat].filter((c) => c === 'E').length;
  if (eCount !== 4) throw new Error(`база должна занимать 4 тайла, найдено ${eCount}`);
  return rows;
}

/** Проверка требований формата, которые легко сломать правкой шаблона. */
function assertPlayable(n, map) {
  const at = (x, y) => map[y][x];
  for (const [x, y] of [[0, 0], [6, 0], [12, 0]]) {
    if (at(x, y) !== '.') throw new Error(`уровень ${n}: точка появления врага (${x},${y}) непроходима`);
  }
  if (at(4, 12) !== '.') throw new Error(`уровень ${n}: точка появления игрока (4,12) непроходима`);
}

const hashes = new Map();
for (let n = 2; n <= 12; n++) {
  const pattern = PATTERNS[n - 2];
  const map = buildMap(pattern);
  assertPlayable(n, map);

  const hash = createHash('sha256').update(map.join('')).digest('hex').slice(8);
  if (hashes.has(hash)) {
    throw new Error(`уровень ${n}: карта совпадает с уровнем ${hashes.get(hash)}`);
  }
  hashes.set(hash, n);

  const level = {
    number: n,
    palette: (n - 1) % 4,
    spawnIntervalSec: Math.max(1.2, +(2.0 - (n - 1) * 0.07).toFixed(2)),
    enemies: enemiesFor(n),
    player: { x: 4, y: 12 },
    enemySpawns: [
      { x: 0, y: 0 },
      { x: 6, y: 0 },
      { x: 12, y: 0 },
    ],
    map,
  };
  const name = String(n).padStart(2, '0') + '.json';
  writeFileSync(join(outDir, name), JSON.stringify(level, null, 2) + '\n', 'utf8');
  console.log(`записан ${name}  карта ${hash}  врагов ${level.enemies.join('')}`);
}
console.log(`готово: ${hashes.size} уровней, все карты уникальны`);
